class RenderEngine
{
public: // Width and height define the size of the screen and buffer saved in memory
    static constexpr int SCREEN_WIDTH = 480;
    static constexpr int SCREEN_HEIGHT = 320;

private:
    // Two buffers are used to avoid screen tearing
    // One is drawn to while the other is being rendered
    uint8_t bufferOne[SCREEN_HEIGHT][SCREEN_WIDTH];
    uint8_t bufferTwo[SCREEN_HEIGHT][SCREEN_WIDTH];

public:
    uint8_t (*drawBuffer)[SCREEN_WIDTH];
    uint8_t (*displayBuffer)[SCREEN_WIDTH];

    RenderEngine()
    {
        drawBuffer    = bufferOne;
        displayBuffer = bufferTwo;
        clear();
    }

    // The simplest form of the render engine. Write a color value to a certain pixel.
    void drawPixel(int x, int y, uint8_t color)
    {
        if (x >= 0 && x < SCREEN_WIDTH && y >= 0 && y < SCREEN_HEIGHT)
        {
            drawBuffer[y][x] = color;
        }
    }

    // Draw a line from a -> b (x1,y1) -> (x2,y2)
    void drawLine(int x1, int y1, int x2, int y2, int lineThickness, uint8_t color)
    {
        int dx = std::abs(x2 - x1);
        int sx = x1 < x2 ? 1 : -1;
        int dy = -std::abs(y2 - y1);
        int sy = y1 < y2 ? 1 : -1;
        int error = dx + dy;

        bool isHorizontal = dx > dy;
        int halfThickness = lineThickness / 2;

        while (true)
        {
            for (int i = -halfThickness; i < halfThickness; i++)
            {
                if (isHorizontal)
                {
                    drawPixel(x1, y1 + i, color);
                } else
                {
                    drawPixel(x1 + 1, y1, color);
                }
            }

            drawPixel(x1, y1, color);
            
            if (x1 == x2 && y1 == y2) break;

            int e2 = 2 * error;
            if (e2 >= dy)
            {
                if (x1 == x2) break;
                error += dy;
                x1 += sx;
            }
            if (e2 <= dx)
            {
                if (y1 == y2) break;
                error += dx;
                y1 += sy;
            }
        }
    }

    void drawRectangle(int x1, int y1, int x2, int y2, uint8_t color)
    {
        for (int j = y1; j < y2; j++)
        {
            for (int i = x1; i < x2; i++)
            {
                drawPixel(i,j,color);
            }
        }
    }

    void drawCircle(int centerX, int centerY, int radius, int thickness, uint8_t color)
    {
        int e = -radius;
        int y = 0;
        int x = radius;

        while (y <= x)
        {
            for (int i = 0; i < thickness; i++)
            {
                drawPixel(centerX + x - i, centerY + y, color);
                drawPixel(centerX - x + i, centerY + y, color);
                drawPixel(centerX + x - i, centerY - y, color);
                drawPixel(centerX - x + i, centerY - y, color);
                drawPixel(centerX + y, centerY + x - i, color);
                drawPixel(centerX - y, centerY + x - i, color);
                drawPixel(centerX + y, centerY - x + i, color);
                drawPixel(centerX - y, centerY - x + i, color);
            }

            e += 2 * y + 1;
            y += 1;
            
            if (e >= 0)
            {
                e -= 2 * x - 1;
                x -= 1;
            }
        }
    }

    void drawChar(int x, int y, char c, int scale, uint8_t color)
    {
        int index = -1;

        // Offset from the ascii characters I stored in this file
        if (c >= ' ' && c <= '~') index = c - 33;

        if (index == -1) return; 

        int fontHeight = 8; 

        for (int row = 0; row < fontHeight; row++)
        {
            uint8_t rowData = minecraftia_regular_font[index][row];
            for (int col = 0; col < 8; col++)
            {
                if (rowData & (1 << (7 - col)))
                {
                    if (scale == 1)
                    {
                        drawPixel(x + col, y + row, color);
                    }
                    else
                    {
                        int xStart = x + (col * scale);
                        int yStart = (y + row) * scale;
                        drawRectangle(xStart, yStart, xStart + scale, yStart + scale, color);
                    }
                }
            }
        }
    }

    void drawText(int x, int y, const char* text, int scale, uint8_t color)
    { // TODO: Debug issue with spacing vertically (y scales, but it shouldnt?)
        int cursorX = x;
        int i = 0;
        
        while (text[i] != '\0')
        {
            drawChar(cursorX, y, text[i], scale, color);
            cursorX += 8*scale-scale;
            i++;
        }
    }

    void clear()
    {
        std::memset(drawBuffer, 0, SCREEN_HEIGHT * SCREEN_WIDTH);
    }

    // Swaps drawing and rendering buffer
    void swapBuffers()
    {
        auto tempPtr  = drawBuffer;
        drawBuffer    = displayBuffer;
        displayBuffer = tempPtr;
    }
};